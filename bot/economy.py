START_BALANCE = 1000
BASE_RATE = 100        # фишек в час
MAX_HOURS = 30         # потолок накопления
HOUR = 3600            # секунд в часе


def accrue(last_accrual, now, rate, max_hours=MAX_HOURS):
    """УСТАРЕВШАЯ часовая логика: в работе не используется (доход идёт поминутно, см. accrue_minutes ниже); нужна только разовой
    миграции db._migrate_minute_accrual и тестам. Возвращает (сколько_начислить, новое_время_последнего_начисления).

    max_hours — потолок накопления игрока (у каждого свой, зависит от уровня хранилища);
    по умолчанию общий MAX_HOURS, поэтому старые вызовы работают как раньше."""
    hours = (now - last_accrual) // HOUR   # целые часы

    if hours <= 0:
        # прошло меньше часа (или часы на сервере "прыгнули назад")
        return 0, last_accrual

    if hours > max_hours:
        # игрока долго не было: платим по потолку, лишнее сгорает
        return max_hours * rate, now

    # сдвигаем время только на целые часы, остаток минут сохраняется
    return hours * rate, last_accrual + hours * HOUR


# ---------- поминутное начисление (ленивое) ----------
# Доход R (фишек в час) начисляется минутными тиками. Сервер считает их лениво: при запросе, затрагивающем игрока, «подтягивает»
# начисление за все полностью прошедшие минуты. У игрока хранятся last_accrual (граница минуты, секунды) и acc (остаток в долях
# фишки, умноженных на 60, всегда от -59 до 0). Каждую минуту: acc += R; credit = ceil(acc / 60), не меньше 0; acc -= credit * 60.
# Сумма за любые 60 минут при неизменном R равна ровно R, расхождение с точным интегралом меньше одной фишки.
# Пакетно, без цикла: кумулятивный кредит после k минут равен ceil((acc0 + k * R) / 60) (acc после каждого шага лежит в
# [-59, 0], значит кумулятивный кредит определяется однозначно), поэтому n минут считаются за O(1).
TICK = 60                     # секунд в минуте начисления
ACC_MIN = -59                 # остаток всегда в [ACC_MIN, 0]
FUTURE_FIX_SECONDS = 365 * 86400   # метка дальше этого срока в будущем считается испорченной и исправляется (без начисления)


def next_tick_in(now):
    """Секунд до следующей минутной границы (от 1 до 60)."""
    return TICK - now % TICK


def per_minute_estimate(rate):
    """Показ «в минуту ≈ N»: rate / 60 с одним знаком после запятой, округление до ближайшего (целыми числами)."""
    tenths = (rate * 10 + 30) // 60
    return "%d.%d" % (tenths // 10, tenths % 10)


def accrue_minutes(last, acc, now, rate, max_hours):
    """Возвращает (сколько_начислить, новая_метка_времени, новый_остаток).

    n = число полностью прошедших минутных границ с last. За n минут платится не больше max_hours * 60 минут (потолок
    офлайн-накопления, лишнее время сгорает, метка переносится на «сейчас»). Нет тиков (n <= 0): ничего не меняется.
    Метка в будущем: ничего не платится; если она дальше FUTURE_FIX_SECONDS, исправляется на текущую минуту (без начисления).
    Некорректный остаток (положительный или ниже -59) приводится в [ACC_MIN, 0]: бесплатных фишек не будет."""
    acc = min(0, max(ACC_MIN, acc))
    rate = max(0, rate)
    n = now // TICK - last // TICK
    if n < 0:
        if -n * TICK > FUTURE_FIX_SECONDS:
            return 0, now // TICK * TICK, acc
        return 0, last, acc
    if n == 0:
        return 0, last, acc
    minutes = min(n, max_hours * 60)
    total = acc + minutes * rate
    credit = max(0, -(-total // 60))
    return credit, now // TICK * TICK, total - 60 * credit
