import os
import re

page = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "privacy.html"), encoding="utf-8").read()

assert "<script" not in page.lower(), "на странице есть script"
assert not re.search(r"https?://|//cdn|\bsrc=|<link|@import|url\(|<iframe|<img", page, re.I), "на странице есть внешние ресурсы"
for label in ("[КОНТАКТ]", "[РЕГИОН]"):
    assert label not in page, "метка вернулась: " + label
assert "crowdad234@gmail.com" in page, "контакт пропал"
assert 'lang="ru"' in page and "<title>Политика конфиденциальности</title>" in page

phrases = [
    # раздел 5
    "Основные данные (баланс, начисления) хранятся, пока работает Сервис или пока вы не попросите их удалить. "
    "История раундов хранится 30 дней, запись об участии в беседе удаляется после 90 дней без заходов в игру из этой беседы.",
    "Обезличенный идентификатор из раздела 2 автоматически удаляется через 30 дней после удаления данных.",
    "Резервные копии базы данных хранятся до 30 дней: удалённые вами данные могут оставаться в них до истечения этого срока.",
    # раздел 7
    "Я автоматически делаю резервные копии базы данных; они хранятся у хостинг-провайдера и у меня.",
    # прежние фразы (защита от повторной регистрации, права на данные) остались
    "в течение 30 дней стартовые 1000 фишек не выдаются, фишки начисляются по 100 в час.",
    "команда /mydata присылает копию ваших данных файлом, а /deletemydata удаляет ваши данные после подтверждения.",
]
for phrase in phrases:
    assert phrase in page, "нет фразы: " + phrase[:60]
assert "Данные хранятся, пока работает Сервис или пока вы не попросите их удалить." not in page, "старое первое предложение раздела 5 осталось"

# фразы находятся в нужных разделах
sec5 = page[page.index("<h2>5."):page.index("<h2>6.")]
sec7 = page[page.index("<h2>7."):page.index("<h2>8.")]
assert "Резервные копии базы данных хранятся до 30 дней" in sec5 and "История раундов хранится 30 дней" in sec5
assert "автоматически делаю резервные копии" in sec7
assert "Дата последнего обновления: 3 октября 2026 г." in page

print("Все проверки прошли")
