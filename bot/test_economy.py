import testenv  # noqa: F401  (первым: очищает окружение проекта и отключает .env)
from economy import accrue, HOUR

T = 1_000_000  # произвольное "время последнего начисления"


def check(name, got, expected):
    assert got == expected, f"{name}: получили {got}, ожидали {expected}"


# 30 минут: ничего не начисляется, время не двигается
check("30 минут", accrue(T, T + 30 * 60, 100), (0, T))

# ровно 1 час
check("1 час", accrue(T, T + HOUR, 100), (100, T + HOUR))

# 2 часа 40 минут: 2 часа начислены, 40 минут остаются "в запасе"
check("2ч 40м", accrue(T, T + 2 * HOUR + 40 * 60, 100), (200, T + 2 * HOUR))

# ровно потолок
check("30 часов", accrue(T, T + 30 * HOUR, 100), (3000, T + 30 * HOUR))

# 50 часов: платим только за 30, остальное сгорает
check("50 часов", accrue(T, T + 50 * HOUR, 100), (3000, T + 50 * HOUR))

# часы "ушли назад": ничего не начисляем
check("время назад", accrue(T, T - 5 * HOUR, 100), (0, T))

# другая скорость (например, после буста)
check("скорость 150", accrue(T, T + 2 * HOUR, 150), (300, T + 2 * HOUR))

print("Все проверки прошли")